const fs=require("fs")
const j=JSON.parse(fs.readFileSync("out/l10n_en.json","utf8"))
const m=new Map()
for(const tb of j.tables) for(const [k,v] of Object.entries(tb.byKey||{})) m.set(k,v)
const clean=s=>String(s).replace(/<color=[^>]*>/g,"").replace(/<\/color>/g,"")
console.log("\n===== 租车 / 车相关 =====")
for(const [k,v] of m) if(/rent|vehicle_rent|car_rent/i.test(k)) console.log("["+k+"] "+clean(v).replace(/\n/g," | ").slice(0,180))
console.log("\n===== 警察追击 / 巡逻 =====")
for(const [k,v] of m) if(/patrol|police_radio|chase|pursuit|cop_car/i.test(k)) console.log("["+k+"] "+clean(v).replace(/\n/g," | ").slice(0,190))
